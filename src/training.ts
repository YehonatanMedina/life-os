export type DayKind = 'easy-run' | 'quality-run' | 'long-run' | 'legs' | 'upper' | 'skills' | 'walk' | 'rest'

/**
 * בודק את מבנה השבוע מול החוקים. מחזיר את ההפרות בשפה שאפשר לתקן לפיה.
 *
 * החוקים ומקורם:
 *   * **עד שני אימוני ריצה איכותיים בשבוע**, ולפחות 48 שעות ביניהם. כל
 *     הניסויים המבוקרים על חלוקת עצימות התכנסו לשניים —
 *     pmc.ncbi.nlm.nih.gov/articles/PMC9299127/ — והתשובה לתקרת 45 הדקות
 *     היא ריצה חמישית, לא אימון קשה שלישי.
 *   * **עד ארבעה ימים קשים**, מתוכם לכל היותר שניים ריצת איכות. יום רגליים
 *     כבד הוא עומס על רקמה אחרת, ולכן הוא נספר בנפרד.
 *   * **אין ריצה קשה ב-24 השעות שאחרי רגליים כבדות** — כלכלת ריצה יורדת
 *     5.6–10%. pubmed.ncbi.nlm.nih.gov/23724883/
 *   * **כוח פלג גוף עליון יכול לחלוק יום עם ריצה** — ההפרעה מקומית לשריר.
 *     pubmed.ncbi.nlm.nih.gov/39921365/
 *   * **הריצה הארוכה לבד.** היא היחידה שלא מוגבלת ב-45 דקות, והיא היקרה
 *     ביותר מבחינת עייפות.
 *   * **לפחות ארבעה ימי ריצה**, וחמישה כשהנפח מצדיק — תדירות היא הדרך
 *     היחידה להעלות נפח מתחת לתקרת זמן.
 *   * **שני ימי סטטיים לא ברצף** — הגיד מסתגל לאט מהשריר.
 *     pmc.ncbi.nlm.nih.gov/articles/PMC4532714/
 */
export function checkWeek(days: DayKind[][]): string[] {
  const bad: string[] = []
  const has = (i: number, k: DayKind) => days[i % 7]?.includes(k)
  const hardDays = days.filter((d) => d.some((k) => k === 'quality-run' || k === 'long-run' || k === 'legs')).length
  if (hardDays > 4) bad.push(`${hardDays} ימים קשים בשבוע — התקרה היא ארבעה`)

  const quality = days.filter((d) => d.includes('quality-run')).length
  if (quality > INTENSITY.qualityRunsPerWeek) {
    bad.push(`${quality} אימוני איכות בשבוע — התקרה היא ${INTENSITY.qualityRunsPerWeek}, והתשובה לתקרת הזמן היא ריצה נוספת ולא אימון קשה נוסף`)
  }

  // מרווח בין ימי האיכות — על מעגל של שבוע, כי ראשון בא אחרי שבת
  const qDays = days.map((d, i) => (d.includes('quality-run') ? i : -1)).filter((i) => i >= 0)
  if (qDays.length === 2) {
    const gap = Math.min(qDays[1] - qDays[0], 7 - (qDays[1] - qDays[0]))
    if (gap * 24 < INTENSITY.minHoursBetweenQuality) bad.push('שני אימוני האיכות קרובים מדי — הרצפה היא 48 שעות')
  }

  for (let i = 0; i < 7; i++) {
    if (has(i, 'legs') && (has(i + 1, 'quality-run') || has(i + 1, 'long-run'))) {
      bad.push(`יום ${i + 1}: רגליים כבדות, ולמחרת ריצה קשה — כלכלת הריצה יורדת ב-24 השעות האלה`)
    }
    if (has(i, 'long-run') && days[i].length > 1) {
      bad.push(`יום ${i + 1}: הריצה הארוכה חולקת יום עם אימון נוסף`)
    }
    if (has(i, 'quality-run') && (has(i + 1, 'quality-run') || has(i + 1, 'long-run'))) {
      bad.push(`יום ${i + 1}: שני ימי ריצה קשים ברצף`)
    }
    if (has(i, 'skills') && has(i + 1, 'skills')) {
      bad.push(`יום ${i + 1}: שני ימי סטטיים ברצף — הגיד מסתגל לאט מהשריר, וצריך 48 שעות`)
    }
  }
  const runs = days.filter((d) => d.some((k) => k.endsWith('run'))).length
  if (runs < WEEK_FLOOR.runDays) bad.push(`${runs} ימי ריצה בשבוע — מתחת לשלוש אין ארוכה, איכות וקלה`)
  return bad
}

