/**
 * חלוקת הנפח השבועי בין **חמישה** ימי ריצה. הארוכה לוקחת את החלק שלה
 * (`longShare`), ומה שנשאר מתחלק בין ימי האיכות לימים הקלים — האיכות מעט
 * ארוכה יותר, כי היא כוללת חימום ושחרור של כ-18 דקות.
 *
 * למה חמישה ימי ריצה ולא ארבעה: תחת תקרת זמן, תדירות היא הדרך היחידה
 * להעלות נפח, וסדר העדיפויות שנמדד הוא תדירות → אורך הארוכה → אימון כפול.
 */
export function splitWeek(weekKm: number): { long: number; quality: number; easy: number; qualityDays: 1 | 2 } {
  const long = Math.round(longShare(weekKm) * 10) / 10
  const rest = Math.max(0, weekKm - long)
  const qualityDays = qualityRuns(weekKm)
  // ארבע ריצות שאינן ארוכות. האיכות מקבלת חלק גדול יותר כי חימום ושחרור
  // נספרים בתוכה; מספר ימי האיכות לא משנה את החלוקה, רק את השמות.
  const quality = Math.round(rest * 0.28 * 10) / 10
  const easy = Math.round(((rest - quality * qualityDays) / (4 - qualityDays)) * 10) / 10
  return { long, quality, easy, qualityDays }
}

